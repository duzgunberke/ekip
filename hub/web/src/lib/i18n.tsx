const tr = Object.fromEntries(Object.keys(en).map((key) => [key, key])) as Record<
  keyof typeof en,
  string
>

const listeners = new Set<() => void>()

function getInitialLanguage(): Language {
  if (typeof window === 'undefined') return 'tr'
  const urlLanguage = new URLSearchParams(window.location.search).get('lang')
  if (urlLanguage === 'en' || urlLanguage === 'tr') return urlLanguage

  try {
    const stored = window.localStorage.getItem('ekip-lang')
    if (stored === 'en' || stored === 'tr') return stored
  } catch {
    // Storage can be unavailable in private browsing; browser language remains a safe fallback.
  }
  return navigator.language.toLowerCase().startsWith('tr') ? 'tr' : 'en'
}

let language: Language = getInitialLanguage()

function subscribe(callback: () => void) {
  listeners.add(callback)
  return () => listeners.delete(callback)
}

export function getLanguage(): Language {
  return language
}

function updateLanguageUrl(value: Language) {
  if (typeof window === 'undefined') return
  const url = new URL(window.location.href)
  url.searchParams.set('lang', value)
  window.history.replaceState(window.history.state, '', url)
}

export function setLanguage(value: Language) {
  if (language === value) {
    updateLanguageUrl(value)
    return
  }
  language = value
  try {
    window.localStorage.setItem('ekip-lang', value)
  } catch {
    // The URL remains the persistent source when storage is unavailable.
  }
  updateLanguageUrl(value)
  document.documentElement.lang = value
  listeners.forEach((listener) => listener())
}

export function translate(
  key: string,
  values?: Record<string, string | number>,
  lang: Language = language
): string {
  const dictionary: Record<string, string> = lang === 'en' ? en : tr
  return (dictionary[key] ?? key).replace(/\{(\w+)\}/g, (_match, name: string) => {
    const value = values?.[name]
    return typeof value === 'number'
      ? new Intl.NumberFormat(lang === 'tr' ? 'tr-TR' : 'en-US').format(value)
      : String(value ?? `{${name}}`)
  })
}

export function useT() {
  const lang: Language = useSyncExternalStore(subscribe, getLanguage, () => 'tr')
  return useCallback(
    (key: string, values?: Record<string, string | number>) => translate(key, values, lang),
    [lang]
  )
}

export function useLanguage() {
  return useSyncExternalStore(subscribe, getLanguage, () => 'tr') as Language
}

export function LanguageSwitcher() {
  const lang = useLanguage()
  return (
    <div role='group' aria-label={translate('Dil seçimi')} className='flex items-center gap-2 text-xs'>
      {(['en', 'tr'] as const).map((value) => (
        <button
          key={value}
          type='button'
          aria-pressed={lang === value}
          aria-label={translate(value === 'en' ? 'İngilizce' : 'Türkçe')}
          className={lang === value ? 'font-semibold text-foreground' : 'text-muted-foreground hover:text-foreground'}
          onClick={() => setLanguage(value)}
        >
          {value.toUpperCase()}
        </button>
      ))}
    </div>
  )
}

export function LanguageSync() {
  const lang = useLanguage()
  const location = useRouterState({ select: (state) => state.location.href })
  useEffect(() => {
    const urlLanguage = new URLSearchParams(window.location.search).get('lang')
    const urlLang: Language | null =
      urlLanguage === 'en' || urlLanguage === 'tr' ? urlLanguage : null
    if (urlLang) {
      if (urlLang !== lang) setLanguage(urlLang)
    } else {
      updateLanguageUrl(lang)
    }
    document.documentElement.lang = lang
  }, [lang, location])
  return null
}

export function formatNumber(value: number): string {
  return new Intl.NumberFormat(language === 'tr' ? 'tr-TR' : 'en-US').format(value)
}

export function formatPercent(value: number): string {
  const formatted = formatNumber(value)
  return language === 'tr' ? `%${formatted}` : `${formatted}%`
}
